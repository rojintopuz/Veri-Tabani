CREATE TABLE eczane (
    eczane_no   INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    ad          VARCHAR(100)    NOT NULL,
    adres       VARCHAR(250),

    CONSTRAINT pk_eczane PRIMARY KEY (eczane_no)
);

CREATE TABLE eczane_telefon (
    eczane_no   INTEGER         NOT NULL,
    telefon_no  VARCHAR(15)     NOT NULL,

    CONSTRAINT pk_eczane_telefon PRIMARY KEY (eczane_no, telefon_no),
    CONSTRAINT fk_eczane_telefon_eczane FOREIGN KEY (eczane_no)
        REFERENCES eczane (eczane_no) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_eczane_telefon_telefon_no CHECK (telefon_no ~ '^0[0-9]{10}$')
);