CREATE TABLE ilac (
    ilac_no     INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    ticari_ad   VARCHAR(100)    NOT NULL,
    formul      VARCHAR(250),

    CONSTRAINT pk_ilac PRIMARY KEY (ilac_no),
    CONSTRAINT uq_ilac_ticari_ad UNIQUE (ticari_ad)
);
