CREATE TABLE doktor (
    doktor_no      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    ad             VARCHAR(100) NOT NULL,
    uzmanlik_alani VARCHAR(100) NOT NULL,
    deneyim_yili   SMALLINT     NOT NULL,
    CONSTRAINT pk_doktor PRIMARY KEY (doktor_no),
    CONSTRAINT ck_doktor_deneyim_yili CHECK (deneyim_yili BETWEEN 0 AND 65)
);