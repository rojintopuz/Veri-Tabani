CREATE TABLE satis (
    satis_id        INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    eczane_no       INTEGER         NOT NULL,
    hasta_kimlik_no CHAR(11)        NOT NULL,
    ilac_no         INTEGER         NOT NULL,
    fiyat           NUMERIC(10,2)   NOT NULL,
    satis_tarihi    DATE            NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_satis PRIMARY KEY (satis_id),
    CONSTRAINT fk_satis_eczane FOREIGN KEY (eczane_no)
        REFERENCES eczane (eczane_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_satis_hasta FOREIGN KEY (hasta_kimlik_no)
        REFERENCES hasta (hasta_kimlik_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_satis_ilac FOREIGN KEY (ilac_no)
        REFERENCES ilac (ilac_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_satis_fiyat CHECK (fiyat >= 0),
    CONSTRAINT uq_satis_eczane_hasta_ilac_tarih UNIQUE (
        eczane_no, hasta_kimlik_no, ilac_no, satis_tarihi
    )
);

CREATE INDEX idx_satis_satis_tarihi ON satis (satis_tarihi);