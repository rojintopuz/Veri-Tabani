CREATE TABLE recete (
    recete_id       INTEGER  GENERATED BY DEFAULT AS IDENTITY,
    doktor_no       INTEGER  NOT NULL,
    hasta_kimlik_no CHAR(11) NOT NULL,
    ilac_no         INTEGER  NOT NULL,
    recete_tarihi   DATE     NOT NULL DEFAULT CURRENT_DATE,
    miktar          INTEGER  NOT NULL,
    CONSTRAINT pk_recete PRIMARY KEY (recete_id),
    CONSTRAINT fk_recete_doktor FOREIGN KEY (doktor_no)
        REFERENCES doktor (doktor_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_recete_hasta FOREIGN KEY (hasta_kimlik_no)
        REFERENCES hasta (hasta_kimlik_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_recete_ilac FOREIGN KEY (ilac_no)
        REFERENCES ilac (ilac_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_recete_doktor_hasta_ilac_tarih UNIQUE (doktor_no, hasta_kimlik_no, ilac_no, recete_tarihi),
    CONSTRAINT ck_recete_miktar CHECK (miktar > 0)
);

CREATE INDEX idx_recete_doktor_no ON recete (doktor_no);
CREATE INDEX idx_recete_hasta_kimlik_no ON recete (hasta_kimlik_no);