CREATE TABLE tedarik_denetim (
    denetim_id      INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    tedarik_id      INTEGER         NOT NULL,
    islem_turu      VARCHAR(10)     NOT NULL,
    eski_miktar     INTEGER,
    yeni_miktar     INTEGER,
    islem_zamani    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tedarik_denetim PRIMARY KEY (denetim_id),
    CONSTRAINT ck_tedarik_denetim_islem_turu CHECK (
        islem_turu IN ('INSERT', 'UPDATE', 'DELETE')
    )
);

CREATE INDEX idx_tedarik_denetim_tedarik_id ON tedarik_denetim (tedarik_id);
