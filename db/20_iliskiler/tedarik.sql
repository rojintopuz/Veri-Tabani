CREATE TABLE tedarik (
    tedarik_id      INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    tedarikci_no    INTEGER         NOT NULL,
    eczane_no       INTEGER         NOT NULL,
    ilac_no         INTEGER         NOT NULL,
    miktar          INTEGER         NOT NULL,
    tedarik_tarihi  DATE            NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_tedarik PRIMARY KEY (tedarik_id),
    CONSTRAINT fk_tedarik_tedarikci FOREIGN KEY (tedarikci_no)
        REFERENCES tedarikci (tedarikci_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tedarik_eczane FOREIGN KEY (eczane_no)
        REFERENCES eczane (eczane_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tedarik_ilac FOREIGN KEY (ilac_no)
        REFERENCES ilac (ilac_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_tedarik_miktar CHECK (miktar > 0),
    CONSTRAINT uq_tedarik_tedarikci_eczane_ilac_tarih UNIQUE (
        tedarikci_no, eczane_no, ilac_no, tedarik_tarihi
    )
);

CREATE INDEX idx_tedarik_tedarik_tarihi ON tedarik (tedarik_tarihi);
CREATE INDEX idx_tedarik_eczane_no_ilac_no ON tedarik (eczane_no, ilac_no);
